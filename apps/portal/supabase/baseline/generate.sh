#!/usr/bin/env bash
# Regenerates schema.sql and product-data.sql from a database that has had WUWF's migration history replayed
# (replay-history.sh) and then cleared with ../install/clear-seed-data-for-new-station.sql.
#
#   PGHOST=... PGPORT=... PGUSER=... PGDATABASE=... ./generate.sh
#
# Needs pg_dump and psql (a Postgres 16 or newer client). It only reads the database it points at.
set -euo pipefail
cd "$(dirname "$0")"
MIG=../migrations
Q() { psql -X -At -v ON_ERROR_STOP=1 -c "$1"; }

# Drops pg_dump's own boilerplate by matching WHOLE lines only. Never filter loosely (by a prefix, or by blank lines):
# a line inside a multi-line string value is data, and an earlier version of this script removed the blank lines from
# the email templates that way. verify.sh compares every kept table row by row to catch exactly that.
noise() { # $1 = schema | data
  local always='\\(un)?restrict [A-Za-z0-9]+|ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT ALL ON (TABLES|FUNCTIONS|SEQUENCES) TO (anon|authenticated|service_role);'
  # The schema keeps its SET lines (check_function_bodies = false is what lets a function mention a table defined later).
  local sets='|SET (statement_timeout|lock_timeout|idle_in_transaction_session_timeout|transaction_timeout) = 0;|SET client_encoding = .UTF8.;|SET standard_conforming_strings = on;|SET check_function_bodies = false;|SET xmloption = content;|SET client_min_messages = warning;|SET row_security = off;'
  if [ "$1" = data ]; then grep -v -x -E "$always$sets" || true; else grep -v -x -E "$always" || true; fi
}

LAST_FILE="$(ls "$MIG"/*.sql | sort | tail -1)"
THROUGH="$(basename "$LAST_FILE" | cut -d_ -f1)"
KEEP="$(awk '/v_keep text\[\] := array\[/,/\];/' ../install/clear-seed-data-for-new-station.sql | grep -o "'[a-z_]*'" | tr -d "'")"
[ -n "$KEEP" ] || { echo "could not read the kept-table list from the clearing script" >&2; exit 1; }

# ---- schema.sql ---------------------------------------------------------------------------------------------
{
  cat <<HDR
-- The Portal's database schema, as a new station installs it. GENERATED by generate.sh; do not edit by hand.
--
-- It is the result of WUWF's migrations through $THROUGH, with the exceptions below, and was checked against
-- WUWF's production database object by object (see README.md). Apply it to an EMPTY Supabase project, once,
-- then product-data.sql. It records itself in Supabase's migration history as version $THROUGH ("baseline"), so in a
-- repository whose migrations folder starts at the baseline the CLI applies only newer migrations. (WUWF's own folder
-- cannot be used that way: three pairs of its files share a version, which the history table cannot record.)
--
-- Postgres owners are left out (the connecting role owns everything, as it does for migrations), and the
-- default privileges Supabase sets up itself are not repeated here.

create extension if not exists vector with schema extensions;

-- Supabase grants anon, authenticated and service_role everything new in public by default. The GRANT and REVOKE
-- statements below are the exact grants the Portal wants, and pg_dump writes them assuming no such default, so switch
-- the defaults off while loading and put them back at the end (the last statements of this file).
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated, service_role;
alter default privileges for role postgres in schema public revoke all on functions from anon, authenticated, service_role;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated, service_role;

HDR
  pg_dump -s -n public -n private --no-owner --no-comments \
    | noise schema \
    | sed -e 's/^CREATE SCHEMA public;$/CREATE SCHEMA IF NOT EXISTS public;/' -e 's/^CREATE SCHEMA private;$/CREATE SCHEMA IF NOT EXISTS private;/'
  cat <<'EXTRA'

-- Back to the normal search path (the dump above empties it).
select pg_catalog.set_config('search_path', '"$user", public, extensions', false);

-- Row level security policies on Supabase Storage's objects table (pg_dump does not include other schemas).
EXTRA
  Q "select format('create policy %I on storage.objects as %s for %s to %s%s%s;',
       polname,
       case when polpermissive then 'permissive' else 'restrictive' end,
       case polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
       (select string_agg(case when u.oid = 0 then 'public' else quote_ident(r.rolname) end, ', ' order by r.rolname) from unnest(polroles) u(oid) left join pg_roles r on r.oid = u.oid),
       case when polqual is not null then ' using (' || pg_get_expr(polqual, polrelid) || ')' else '' end,
       case when polwithcheck is not null then ' with check (' || pg_get_expr(polwithcheck, polrelid) || ')' else '' end)
     from pg_policy where polrelid = 'storage.objects'::regclass order by polname"
  cat <<'EXTRA'

-- Triggers on Supabase Auth's users table (they call functions defined above).
EXTRA
  Q "select pg_get_triggerdef(t.oid) || ';' from pg_trigger t where t.tgrelid = 'auth.users'::regclass and not t.tgisinternal order by t.tgname"
  cat <<'EXTRA'

-- Record this baseline as one applied migration (below), so a later "supabase db push" in a repository whose
-- migrations folder starts at the baseline applies only newer files.
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version text primary key, statements text[], name text
);
EXTRA
  echo "insert into supabase_migrations.schema_migrations (version, name) values ('$THROUGH', 'baseline') on conflict (version) do nothing;"
  cat <<'EXTRA'

-- Supabase's standard defaults for new objects in public, restored for the migrations that come after this file.
alter default privileges for role postgres in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges for role postgres in schema public grant all on functions to anon, authenticated, service_role;
alter default privileges for role postgres in schema public grant all on sequences to anon, authenticated, service_role;
EXTRA
} > schema.sql

# ---- product-data.sql ---------------------------------------------------------------------------------------
{
  cat <<HDR
-- The data every station starts with: the tool registry, the product's Resources guides, Sourcework's piece
-- formats, the pitch form, generic industry categories, neutral settings rows and the storage buckets.
-- GENERATED by generate.sh from the migrations through $THROUGH after the clearing script; do not edit by hand.
-- Apply after schema.sql, once, to an empty database. No account, station name or WUWF data is in it.

begin;
HDR
  for t in $KEEP; do
    n="$(Q "select count(*) from public.$t")"
    [ "$n" != "0" ] && echo "alter table public.$t disable trigger user;"
  done
  # sw_piece_formats and its versions point at each other (a format's live version; a version's format) and the
  # constraint is not deferrable, so pg_dump cannot order them. Load the formats without the pointer, then the
  # versions, then set the pointers.
  # shellcheck disable=SC2046
  pg_dump -a --column-inserts --rows-per-insert=20 --no-owner \
      $(for t in $KEEP; do case "$t" in sw_piece_formats|sw_piece_format_versions) ;; *) echo "-t public.$t";; esac; done) \
    | noise data
  Q "select format('insert into public.sw_piece_formats select * from jsonb_populate_recordset(null::public.sw_piece_formats, %L::jsonb);', coalesce(jsonb_agg(to_jsonb(f) - 'live_version_id' order by f.id), '[]'::jsonb)::text) from public.sw_piece_formats f"
  Q "select format('insert into public.sw_piece_format_versions select * from jsonb_populate_recordset(null::public.sw_piece_format_versions, %L::jsonb);', coalesce(jsonb_agg(to_jsonb(v) order by v.id), '[]'::jsonb)::text) from public.sw_piece_format_versions v"
  Q "select format('update public.sw_piece_formats f set live_version_id = x.live_version_id from jsonb_to_recordset(%L::jsonb) as x(id uuid, live_version_id uuid) where f.id = x.id;', coalesce(jsonb_agg(jsonb_build_object('id', id, 'live_version_id', live_version_id) order by id), '[]'::jsonb)::text) from public.sw_piece_formats"
  for t in $KEEP; do
    n="$(Q "select count(*) from public.$t")"
    [ "$n" != "0" ] && echo "alter table public.$t enable trigger user;"
  done
  echo "-- Storage buckets (their policies are in schema.sql)."
  Q "select 'insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (' || string_agg(format('%L, %L, %L, %L, %L', id, name, public, file_size_limit, allowed_mime_types), '), (') || ') on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;' from storage.buckets"
  echo "commit;"
} > product-data.sql

echo "$THROUGH" > BASELINE_THROUGH
wc -l schema.sql product-data.sql BASELINE_THROUGH
